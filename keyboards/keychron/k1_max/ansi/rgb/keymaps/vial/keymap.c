// clang-format on
bool process_record_user(uint16_t keycode, keyrecord_t *record) {
    if (!process_record_keychron_common(keycode, record)) {
        return false;
    }

    // Start My Mode Swap
    if (IS_QK_MODE_SWAP(keycode)) {
        return process_mode_swap(QK_MODE_SWAP_GET_LAYER1(keycode), QK_MODE_SWAP_GET_LAYER2(keycode), record);
    }
    // End My Mode Swap

    return true;
}
