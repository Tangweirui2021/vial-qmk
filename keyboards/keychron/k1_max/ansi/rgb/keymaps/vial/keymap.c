// Start My Mode Swap
#define QK_MODE_SWAP 0x5300
#define QK_MODE_SWAP_MAX 0x53FF
#define IS_QK_MODE_SWAP(keycode) ((keycode) >= QK_MODE_SWAP && (keycode) <= QK_MODE_SWAP_MAX)
#define MODE_SWAP(layer1, layer2) (QK_MODE_SWAP | (((layer1) & 0xF) << 4) | ((layer2) & 0xF))
#define QK_MODE_SWAP_GET_LAYER1(keycode) (((keycode) >> 4) & 0xF)
#define QK_MODE_SWAP_GET_LAYER2(keycode) ((keycode) & 0xF)

static bool process_mode_swap(uint8_t layer1, uint8_t layer2, keyrecord_t *record) {
    if (record->event.pressed) {
        uint8_t current_default_layer = get_highest_layer(default_layer_state);

        if (current_default_layer == layer1) {
            set_single_persistent_default_layer(layer2);
        } else if (current_default_layer == layer2) {
            set_single_persistent_default_layer(layer1);
        }
    }

    return false;
}
// End My Mode Swap

